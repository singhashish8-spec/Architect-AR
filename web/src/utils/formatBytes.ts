// Human-readable byte counts for upload progress ("45.2 MB of 198.3 MB"),
// matching how a browser's own download manager shows a transfer in
// progress -- the owner's own reference point when asking for this.
export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`
  const units = ['KB', 'MB', 'GB']
  let value = bytes / 1024
  let unitIndex = 0
  while (value >= 1024 && unitIndex < units.length - 1) {
    value /= 1024
    unitIndex += 1
  }
  return `${value.toFixed(1)} ${units[unitIndex]}`
}
